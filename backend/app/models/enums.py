from enum import StrEnum


class Role(StrEnum):
    ADMIN = "ADMIN"
    ANALYST = "ANALYST"
    MANAGER = "MANAGER"
    AUDITOR = "AUDITOR"


class BECType(StrEnum):
    EXECUTIVE_IMPERSONATION = "EXECUTIVE_IMPERSONATION"
    VENDOR_FRAUD = "VENDOR_FRAUD"
    BANK_ACCOUNT_CHANGE = "BANK_ACCOUNT_CHANGE"
    SENSITIVE_DATA_REQUEST = "SENSITIVE_DATA_REQUEST"
    OTHER = "OTHER"


class RiskLevel(StrEnum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class AnalysisStatus(StrEnum):
    COMPLETED = "COMPLETED"
    ERROR = "ERROR"


class AlertStatus(StrEnum):
    OPEN = "OPEN"
    UNDER_REVIEW = "UNDER_REVIEW"
    CLOSED = "CLOSED"


class AlertVerdict(StrEnum):
    CONFIRMED_BEC = "CONFIRMED_BEC"
    FALSE_POSITIVE = "FALSE_POSITIVE"
